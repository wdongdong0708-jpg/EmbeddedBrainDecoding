"""Export reparameterized INT8 models to C99 static weight headers (`model_weights.h`) and layer profiling reports."""

from __future__ import annotations

import copy
import json
from pathlib import Path
from typing import Dict, List
import numpy as np
import torch
import torch.nn as nn

from ..lexicon import CODEBOOK_CONSONANTS, CODEBOOK_TONES, POLARIZED_SUBSET_4_INDICES
from ..models.quantization import QATConv2d, QATLinear, compute_sqnr_db


def unwrap_qat_modules(model: nn.Module) -> nn.Module:
    """Replace QATConv2d / QATLinear wrappers in-place with their underlying Conv2d / Linear modules."""
    for name, child in list(model.named_children()):
        if isinstance(child, QATConv2d):
            setattr(model, name, child.conv)
        elif isinstance(child, QATLinear):
            setattr(model, name, child.linear)
        else:
            unwrap_qat_modules(child)
    return model


def _format_c_array_int8(name: str, arr: np.ndarray) -> str:
    flat = arr.reshape(-1).astype(np.int8)
    vals = ", ".join(str(int(v)) for v in flat)
    return f"static const int8_t {name}[{len(flat)}] = {{ {vals} }};\n"


def _format_c_array_int32(name: str, arr: np.ndarray) -> str:
    flat = arr.reshape(-1).astype(np.int32)
    vals = ", ".join(str(int(v)) for v in flat)
    return f"static const int32_t {name}[{len(flat)}] = {{ {vals} }};\n"


def _format_c_array_float(name: str, arr: np.ndarray) -> str:
    flat = arr.reshape(-1).astype(np.float32)
    vals = ", ".join(f"{float(v):.8e}f" for v in flat)
    return f"static const float {name}[{len(flat)}] = {{ {vals} }};\n"


@torch.no_grad()
def export_model_to_c_header(
    model: nn.Module,
    export_dir: Path,
    model_prefix: str = "edge_eeg_stage2",
) -> Dict[str, object]:
    """
    1. Unwrap any QAT wrappers and execute `deploy_reparameterize()` if supported.
    2. Quantize all Conv2d and Linear layers to Per-Channel Symmetric INT8 (`int8_t`).
    3. Write `model_weights.h` and `export_report.json` to `export_dir`.
    """
    export_dir.mkdir(parents=True, exist_ok=True)
    clean_model = copy.deepcopy(model).cpu().eval()
    unwrap_qat_modules(clean_model)
    if hasattr(clean_model, "deploy_reparameterize"):
        clean_model.deploy_reparameterize()

    c_lines: List[str] = [
        "/* Auto-generated by edge_eeg.engine.exporter — DO NOT EDIT MANUALLY */",
        "#ifndef EDGE_EEG_MODEL_WEIGHTS_H_",
        "#define EDGE_EEG_MODEL_WEIGHTS_H_",
        "",
        "#include <stdint.h>",
        "",
    ]

    layer_reports: List[Dict[str, object]] = []
    total_int8_bytes = 0
    total_bias_bytes = 0

    for mod_name, mod in clean_model.named_modules():
        if not isinstance(mod, (nn.Conv2d, nn.Linear)):
            continue
        safe_name = f"{model_prefix}_{mod_name.replace('.', '_')}"
        w_fp32 = mod.weight.detach().float()
        out_c = w_fp32.size(0)
        w_flat = w_fp32.view(out_c, -1)
        max_val = torch.amax(torch.abs(w_flat), dim=1).clamp(min=1e-8)
        w_scale = max_val / 127.0
        shape = [-1] + [1] * (w_fp32.dim() - 1)
        w_q = torch.clamp(torch.round(w_fp32 / w_scale.view(*shape)), -127.0, 127.0).to(torch.int8)
        w_deq = w_q.float() * w_scale.view(*shape)
        sqnr = compute_sqnr_db(w_fp32, w_deq)

        if mod.bias is not None:
            b_fp32 = mod.bias.detach().float()
            # Quantize bias with finest scale (w_scale * typical input scale 1/32)
            b_scale = (w_scale / 32.0).clamp(min=1e-9)
            b_q = torch.round(b_fp32 / b_scale).to(torch.int32)
        else:
            b_q = torch.zeros(out_c, dtype=torch.int32)

        w_np = w_q.numpy()
        b_np = b_q.numpy()
        s_np = w_scale.numpy()

        c_lines.append(f"/* Layer: {mod_name} | shape={list(w_fp32.shape)} | SQNR={sqnr:.2f} dB */")
        c_lines.append(_format_c_array_int8(f"{safe_name}_weights", w_np))
        c_lines.append(_format_c_array_int32(f"{safe_name}_bias", b_np))
        c_lines.append(_format_c_array_float(f"{safe_name}_scales", s_np))

        w_bytes = int(w_np.size)
        b_bytes = int(b_np.size * 4)
        total_int8_bytes += w_bytes
        total_bias_bytes += b_bytes

        layer_info: Dict[str, object] = {
            "layer": mod_name,
            "type": type(mod).__name__,
            "shape": list(w_fp32.shape),
            "int8_weight_bytes": w_bytes,
            "int32_bias_bytes": b_bytes,
            "weight_sqnr_db": round(sqnr, 2),
        }
        if isinstance(mod, nn.Conv2d):
            layer_info["groups"] = mod.groups
            layer_info["dilation"] = list(mod.dilation)
            layer_info["stride"] = list(mod.stride)
        layer_reports.append(layer_info)

    # Export Stage 3 12-Sentence & 4-Sentence Codebook Lookup Tables
    c_lines.append("/* Stage 3 Mandarin Command Codebook Lookup Tables (12 sentences x 4 syllables) */")
    c_lines.append(_format_c_array_int8("edge_codebook_12_tones", CODEBOOK_TONES))
    c_lines.append(_format_c_array_int8("edge_codebook_12_consonants", CODEBOOK_CONSONANTS))
    c_lines.append(
        _format_c_array_int8(
            "edge_polarized_4_indices",
            np.array(POLARIZED_SUBSET_4_INDICES, dtype=np.int8),
        )
    )
    c_lines.append("#endif /* EDGE_EEG_MODEL_WEIGHTS_H_ */\n")

    header_path = export_dir / "model_weights.h"
    header_path.write_text("\n".join(c_lines), encoding="utf-8")

    report = {
        "model_prefix": model_prefix,
        "header_path": str(header_path),
        "total_int8_weight_bytes": total_int8_bytes,
        "total_int8_weight_kb": round(total_int8_bytes / 1024.0, 2),
        "total_int32_bias_bytes": total_bias_bytes,
        "layers": layer_reports,
    }
    report_path = export_dir / "export_report.json"
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(
        f"[exporter] Exported {len(layer_reports)} fused INT8 layers "
        f"({total_int8_bytes} bytes = {total_int8_bytes/1024.0:.2f} KB Flash) -> {header_path}"
    )
    return report
